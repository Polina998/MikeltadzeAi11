print("--- Калькулятор оценок ---")
print("Чтобы выйти из программы, введите 'выход' вместо числа")

while True:
    a_str = input("\nВведите первое число: ")
    
    if a_str.lower() == 'выход':
        print("Программа завершена.")
        break
        
    b_str = input("Введите второе число: ")
    a = int(a_str)
    b = int(b_str)

    s = a + b
    st = a ** b
    
    print("Сумма:", s)
    print("Степень:", st)

    if b == 0:
        print("Деление: Ошибка! На ноль делить нельзя.")
        print("Остаток: Ошибка! На ноль делить нельзя.")
        print("Среднее: Ошибка! На ноль делить нельзя.")
    else:
        d = a / b
        o = a % b
        sr = (a + b) / 2
        print("Деление:", d)
        print("Остаток:", o)
        print("Среднее:", sr)

        if sr >= 5:
            print("Высокий результат")
